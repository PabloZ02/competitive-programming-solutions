v<ll> M(40,-1);
ll solve(int n) {
    if (n < 0) return 0;
    else if (n == 0) return 1;
    else if (M[n] != -1) return M[n];
    else return M[n] = solve(n-1) + 4*solve(n-2) + 2*solve(n-3);
}
