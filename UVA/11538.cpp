int main() {
    ios_base::sync_with_stdio(0); cin.tie(0);

    
    ll n,m;
    while(1) {
        cin >> n >> m;
        if (n == 0) break;
        ll ans = 0;
        ll d = min(n,m);
        ll dcant = n+m-1;
        ans -= 2*(d-1)*(d);
        ans += m*(n-1)*n + n*(m-1)*m;
        
        ans += ((d-1)*(d)*(2*d-1)/3 + (dcant-2*(d-1))*d*(d-1))*2;
        cout << ans << "\n";
    }
}
